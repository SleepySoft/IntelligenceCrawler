# -*- coding: utf-8 -*-
"""
CrawlerCodeGenerator — 扁平配置代码生成器

设计目标：
- 直接消费扁平 CRAWLER_CONFIG 结构
- 使用 pprint.pformat() 替代模板字符串拼接
- 无需维护 _generate_*_code() 辅助方法
- 新增字段自动生成，无需修改 Generator
"""
import ast
import inspect
import pprint
import textwrap


USAGE_FOOTER = '''
# ------ Usage example and demo. Can be deleted. ------

if __name__ == "__main__":
    import traceback
    try:
        from IntelligenceCrawler.CrawlPipeline import run_pipeline, save_article_to_disk
        CRAWLER_CONFIG['content_handler'] = save_article_to_disk
        run_pipeline('default', CRAWLER_CONFIG)
    except Exception as e:
        print(str(e))
        print(traceback.format_exc())
'''


class CrawlerCodeGenerator:
    """Generates executable Python code from a flat CRAWLER_CONFIG dictionary."""

    def generate_code_from_config(self, config: dict) -> str:
        """
        Takes a **flat** configuration dict (as produced by Playground's
        _build_flat_config_dict) and generates a Python script containing
        CRAWLER_CONFIG.

        Args:
            config: Flat dict with keys like d_fetcher_name, discoverer_name,
                    entry_points, period_filter, etc.

        Returns:
            Executable Python code string.
        """
        # Replace callables with marker strings before pprint, then put their
        # source definitions before CRAWLER_CONFIG. This keeps a loaded custom
        # article_filter executable after Playground saves it again.
        MARKER_PRINT = "__PY_BARE_PRINT__"
        callable_markers = {}
        callable_sources = []

        def _lambda_expression(function) -> str:
            source = textwrap.dedent(inspect.getsource(function)).strip()
            start = source.find("lambda")
            if start < 0:
                raise ValueError(f"Cannot recover lambda source for {function!r}.")
            expression = source[start:].rstrip().rstrip(",").strip()
            try:
                ast.parse(expression, mode="eval")
            except SyntaxError as exc:
                raise ValueError(
                    f"Cannot safely serialize lambda {function!r}; use a module-level def function."
                ) from exc
            return expression

        def _replace_callables(obj):
            if callable(obj) and obj is print:
                return MARKER_PRINT
            if callable(obj):
                marker = callable_markers.get(id(obj))
                if marker:
                    return marker[0]
                if not inspect.isfunction(obj):
                    raise ValueError(
                        "Crawler config contains a callable that cannot be serialized: "
                        f"{obj!r}. Use a module-level def function."
                    )
                if obj.__code__.co_freevars:
                    raise ValueError(
                        f"Crawler config callable {obj.__name__!r} closes over local state; "
                        "use a self-contained module-level function."
                    )
                marker = f"__PY_CALLABLE_{len(callable_markers)}__"
                reference_name = obj.__name__
                if reference_name == "<lambda>":
                    reference_name = f"_crawler_callable_{len(callable_markers)}"
                    source = f"{reference_name} = {_lambda_expression(obj)}"
                else:
                    source = textwrap.dedent(inspect.getsource(obj)).strip()
                callable_markers[id(obj)] = (marker, reference_name)
                callable_sources.append(source)
                return marker
            if isinstance(obj, dict):
                return {k: _replace_callables(v) for k, v in obj.items()}
            if isinstance(obj, (list, tuple)):
                replaced = [_replace_callables(v) for v in obj]
                return type(obj)(replaced)
            return obj

        sanitized = _replace_callables(config)
        config_str = pprint.pformat(sanitized, indent=4, width=100, sort_dicts=False)
        config_str = config_str.replace(f"'{MARKER_PRINT}'", "print")
        for marker, name in callable_markers.values():
            config_str = config_str.replace(repr(marker), name)

        definitions = ""
        if callable_sources:
            definitions = "\n\n".join(callable_sources) + "\n\n"

        return f"""# CrawlerConfig.py - This configuration is generated by CrawlerPlayground
import datetime

{definitions}# === Crawler Configuration ===
CRAWLER_CONFIG = {config_str}
{USAGE_FOOTER}"""
